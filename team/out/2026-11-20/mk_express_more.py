C = [[AV, CS], [SA, LO, NA], [AB, AM, SC]]
def fmt(x): return ('%.2f' % x).replace('.', ',')
coupons, msgs = [], []
for n, legs in enumerate(C, 13):
    legs = sorted(legs, key=lambda l: l['time'])
    k = round(__import__('math').prod(l['kef'] for l in legs), 2)
    coupons.append(dict(size=len(legs), legs=[{x: v for x, v in l.items() if x != 'why'} for l in legs], kef=k,
                        p=round(__import__('math').prod(l['p'] for l in legs), 4)))
    t = ['КХЛ · 20 ноября · экспресс', '']
    for j, l in enumerate(legs, 1):
        t += ['%d. <b>%s — %s</b>, %s МСК' % (j, l['home'], l['away'], l['time']),
              '%s · %s' % (l['bet_full'], fmt(l['kef'])), '<i>Почему:</i> ' + l['why'], '']
    t += ['Общий кэф: <b>%s</b>' % fmt(k), '', '#кхл #экспресс #jarvibet']
    text = '\n'.join(t)
    assert len(text) <= 1024, (n, len(text))
    msgs.append({"to": "owner", "type": "animation", "html": True, "files": ["out/express/2026-11-20-more/e%d_anim.mp4" % (n - 12)],
                 "text": text, "buttons": "post", "pid": "2011-e%d" % n})
    print(len(text), text, '\n----')
