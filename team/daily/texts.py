def banks():
    """Все банки движку (variety.Engine). Окна: фразы — 7 дней, обращения — 4 дня (по два в день: утро и итоги),
    макеты — 3 дня (подряд не повторяются; итоги в тот же день — не тем же макетом, что утро)."""
    b = {
        'm.layout': Bank(MORNING_LAYOUTS, window=3),
        'r.layout': Bank(RECAP_LAYOUTS, window=3, exclude_same_day='m.layout'),
        'addr': Bank(ADDR, per_day=2, window=4),
        'm.head': Bank(M_HEAD), 'm.hello': Bank(M_HELLO), 'm.nhlbig': Bank(M_NHLBIG),
        'm.khl_times': Bank(M_KHL_TIMES), 'm.nhl_times': Bank(M_NHL_TIMES), 'm.derby': Bank(M_DERBY),
        'm.cta': Bank(M_CTA), 'm.picks': Bank(M_PICKS), 'm.close': Bank(M_CLOSE),
        'm.num': Bank(M_NUM, when=_on('m', 'number')),
        'm.wd.mon': Bank(M_WD['mon'], window=15, when=_wd(0)),
        'm.wd.mid': Bank(M_WD['mid'], window=7, when=_wd(1, 2, 3)),
        'm.wd.fri': Bank(M_WD['fri'], window=15, when=_wd(4)),
        'm.wd.sat': Bank(M_WD['sat'], window=15, when=_wd(5)),
        'm.wd.sun': Bank(M_WD['sun'], window=15, when=_wd(6)),
        'r.head': Bank(R_HEAD), 'r.hello': Bank(R_HELLO), 'r.count': Bank(R_COUNT), 'r.trans': Bank(R_TRANS),
        'r.units': Bank(R_UNITS), 'r.week': Bank(R_WEEK), 'r.ret': Bank(R_RET),
        'r.week_done': Bank(R_WEEK_DONE, window=15, when=_wd(0)),
        'r.num': Bank(R_NUM, when=_on('r', 'number')),
    }
    for k, v in M_DAY.items():
        b['m.day.' + k] = Bank(v)
    for k, v in R_RES.items():
        b['r.res.' + k] = Bank(v)
    for k, v in R_CLOSE.items():
        b['r.close.' + k] = Bank(v)
